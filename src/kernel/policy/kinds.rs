//! Exception names, legacy spellings and retired-kind interpretation.

/// A requirement was skipped: a Python requirement that is project-local or
/// a direct reference, or an optional Node dependency ward cannot verify (no
/// integrity, a non-https tarball, a local reference the lock cannot place),
/// which is left out of the tree rather than installed unverified, or an npm
/// workspace member reached through a symlink that leads outside the project.
pub const REQUIREMENT_SKIPPED: &str = "requirement-skipped";
/// Two wheels shipped the same path (the later wheel won), or two Node
/// packages in one `node_modules` claimed one bin name (the first kept it).
pub const FILE_COLLISION: &str = "file-collision";
/// An install lifecycle script failed but its extracted package was retained.
pub const INSTALL_SCRIPT_FAILED: &str = "install-script-failed";
/// A legacy SHA-1 lock integrity was accepted and verified.
pub const WEAK_INTEGRITY: &str = "weak-integrity";
/// A mutable projection was created without attesting its runtime contents.
pub const UNATTESTED_MUTABLE_STATE: &str = "unattested-mutable-state";
/// A future git dependency was accepted without registry provenance.
pub const GIT_DEPENDENCY: &str = "git-dependency";
/// Retired: an optional dependency group the user did not request. It is
/// a choice, not something ward could not vouch for, so it is recorded as an
/// `OptionalGroupSkipped` in the closure's `optional_groups_skipped` list.
pub const SKIPPED_OPTIONAL: &str = "skipped-optional";
/// A manifest named a private index or an index-like option.
pub const UNATTESTED_INDEX: &str = "unattested-index";
/// A lock's content digest did not match its source manifest.
pub const LOCK_DISAGREEMENT: &str = "lock-disagreement";
/// A Cargo.lock was generated by the store Cargo rather than shipped by the
/// source archive.
pub const UNATTESTED_CARGO_LOCK: &str = "unattested-cargo-lock";
/// An install-time download was skipped; the artifact is not in the closure.
pub const ARTIFACT_NOT_PROVISIONED: &str = "artifact-not-provisioned";
/// ward downloaded and verified an install-time artifact itself; the
/// checksum source is upstream's own manifest (trust-on-first-use).
pub const ARTIFACT_PROVISIONED: &str = "artifact-provisioned";
/// A package that ships prebuilt binaries was compiled from source instead.
pub const BUILT_FROM_SOURCE: &str = "built-from-source";
/// The toolchain is a directory on this machine (rustup's `[toolchain]
/// path`), locked by its content hash, not a pinned catalog release.
pub const EXTERNAL_TOOLCHAIN: &str = "external-toolchain";
/// A native extension did not build against the host's C runtime alone and
/// was rebuilt against the machine's whole `/usr`, so the object depends on
/// which development packages the building host has installed.
pub const HOST_BUILD_INPUTS: &str = "host-build-inputs";
/// The resolution proxy served registry metadata from its last good copy
/// because the registry was unreachable (a transport failure or offline
/// mode). The subject is the endpoint; the detail counts the responses.
pub const STALE_RESOLUTION: &str = "stale-resolution";
/// A resolution tool ran without its network fenced to ward's proxy (the
/// `isolated` tier), so the ledger may be missing traffic the tool sent.
pub const UNCONFINED_RESOLUTION: &str = "unconfined-resolution";
/// A lock has no attesting resolution record at closure time: it did not
/// come from a ward resolution door whose signed receipt a trusted key vouches
/// for, or the receipt no longer matches the files on disk.
pub const UNRECORDED_RESOLUTION: &str = "unrecorded-resolution";
/// Resolution could not complete without building a third-party source
/// distribution, and the build was allowed.
pub const RESOLUTION_BUILD: &str = "resolution-build";
/// A required package whose `os`/`cpu`/`libc` excludes this host was placed
/// anyway, because the package manager that wrote the lock places it. Its
/// files are verified like any other package's; its install scripts are not
/// run.
pub const FOREIGN_PLATFORM_PACKAGE: &str = "foreign-platform-package";
/// A git source the lock names was fetched over `ssh://` (offering this
/// machine's ssh agent keys, under its ssh configuration) or read from a
/// `file://` path on this machine. The content is still pinned by commit;
/// what the lock chose is which host or path the sync reaches, and with
/// which credentials. The subject is the URL.
pub const HOST_GIT_TRANSPORT: &str = "host-git-transport";
/// The lock pinned no digest for a package (a `Gemfile.lock` without a
/// `CHECKSUMS` section), so its bytes were verified against the digest the
/// registry's API served on first use, or ward's store record of that
/// answer. The subject is the package.
pub const UNPINNED_DIGEST: &str = "unpinned-digest";
/// A lifecycle script of the project itself or of one of its workspace
/// members (`preinstall`, `install`, `postinstall`, `prepare`) that npm
/// would run on install and ward did not. ward runs dependencies' scripts
/// in the sandbox, but these write the project's own source, which no store
/// object may hold. The subject is the directory, the detail the script.
pub const PROJECT_SCRIPT_SKIPPED: &str = "project-script-skipped";
/// A registry package version the resolution locked was published less
/// than the policy's minimum age before that resolution (`[packages]
/// min_age_days`, 7 days when no policy sets it), or its publish time could
/// not be learned. Judged when the lock is resolved, from the registry's own
/// timestamp for the exact version; the signed resolution record carries the
/// finding, so every later sync and `ward audit` replays it. The subject is
/// `name@version`, the detail the publish time, the resolution time and the
/// minimum.
pub const YOUNG_PACKAGE: &str = "young-package";
/// A locked registry package's name is one edit (an insertion, a deletion,
/// a substitution, or two neighbours swapped) from the name of one of its
/// ecosystem's most popular packages without being that package: a typo, or
/// a name chosen to be mistaken for the popular one. A heuristic, recorded
/// at every sync. The subject is the name, the detail the popular name.
pub const LOOKALIKE_NAME: &str = "lookalike-name";
/// A symlink in a project whose manifest is code (a Gemfile, a mix.exs, a
/// csproj) leads out of the project, or through an entry the resolver's
/// copy leaves out, so the resolver ran without it: the link was left out
/// of its copy of the project. The resolution record still names the link
/// by its target text. A manifest, lock or configuration file that is such
/// a link is refused instead. The subject is the link's path, the detail
/// its target.
pub const OUTWARD_SYMLINK: &str = "outward-symlink";

