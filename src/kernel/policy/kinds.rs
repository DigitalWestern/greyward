/// Kinds that describe the project, its lock or its resolution rather than
/// the bytes of an object built from them. The planner, the resolution join
/// or the projection records each one again on every sync, warm or cold, so
/// a store object never carries one: an environment shared by two projects
/// must not replay one project's lock findings onto the other. Every other
/// kind recorded while an object is realized is stored with it, so a cache
/// hit replays it and a stricter policy refuses the object (`object_exceptions`).
pub const PLAN_TIME_KINDS: &[&str] = &[
    REQUIREMENT_SKIPPED,
    WEAK_INTEGRITY,
    UNATTESTED_MUTABLE_STATE,
    UNATTESTED_INDEX,
    LOCK_DISAGREEMENT,
    STALE_RESOLUTION,
    UNCONFINED_RESOLUTION,
    UNRECORDED_RESOLUTION,
    RESOLUTION_BUILD,
    FOREIGN_PLATFORM_PACKAGE,
    PROJECT_SCRIPT_SKIPPED,
    YOUNG_PACKAGE,
    LOOKALIKE_NAME,
    OUTWARD_SYMLINK,
];

/// Kinds were spelled with two separators until the names were unified on
/// the hyphen. Policy files and closure records written under the old
/// spellings keep working: every kind is read through `canonical_kind`, so
/// a deny list and a record that disagree about the separator still judge
/// the same way. Nothing writes the left-hand spelling any more.
const LEGACY_KIND_SPELLINGS: &[(&str, &str)] = &[
    ("skipped_optional", SKIPPED_OPTIONAL),
    ("unattested_index", UNATTESTED_INDEX),
    ("lock_disagreement", LOCK_DISAGREEMENT),
    ("unattested_cargo_lock", UNATTESTED_CARGO_LOCK),
    ("artifact_not_provisioned", ARTIFACT_NOT_PROVISIONED),
    ("artifact_provisioned", ARTIFACT_PROVISIONED),
    ("built_from_source", BUILT_FROM_SOURCE),
];

/// Kinds nothing records any more, each with what a record carrying it
/// means now. A deny list may still name one: denying what cannot occur is
/// satisfied by every record, so the entry is dropped rather than refused,
/// and a policy file written for an older ward keeps loading. A closure that
/// still records one is known to be old, not from a newer ward: `ward audit`
/// reports it outdated with the reason here. `toolchain-component-unavailable`
/// was a requested Rust component ward did not ship; ward now provisions
/// every component the pinned release publishes and refuses the rest.
/// `skipped-optional` was an optional dependency group the user did not
/// request; it is a choice, not an exception, and the closure now lists it
/// under `optional_groups_skipped` (#71).
pub(super) const RETIRED_KINDS: &[(&str, &str)] = &[
    (
        "toolchain-component-unavailable",
        "closure predates component provisioning",
    ),
    (
        SKIPPED_OPTIONAL,
        "closure predates optional_groups_skipped; unrequested optional groups are no longer exceptions",
    ),
];

/// Why a record of `kind` is out of date, when `kind` is one ward retired.
pub fn retired_kind(kind: &str) -> Option<&'static str> {
    RETIRED_KINDS
        .iter()
        .find(|(retired, _)| *retired == canonical_kind(kind))
        .map(|(_, why)| *why)
}

/// The one spelling of `kind` this binary judges, denies, and prints. An
/// unknown kind is returned unchanged: a record from a newer ward must stay
/// unknown rather than be folded into a kind this binary does know.
pub fn canonical_kind(kind: &str) -> &str {
    LEGACY_KIND_SPELLINGS
        .iter()
        .find(|(legacy, _)| *legacy == kind)
        .map_or(kind, |(_, canonical)| *canonical)
}
