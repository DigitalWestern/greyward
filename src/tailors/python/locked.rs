//! The PyPI packages a uv run's lock names, for the door's `young-package`
//! check (`kernel::resolve::age`): every `uv.lock` package from the public
//! index, and every pinned line of a compiled requirements file (uv
//! compiles those against PyPI alone). Git, path and URL requirements are
//! left out.

use super::manifest::uv_pypi_packages;
use crate::kernel::resolve::age::LockedPackage;
use crate::kernel::resolve::door::{LockedList, Staged};
use std::io;
use std::path::PathBuf;

/// The first line of a requirements file `uv pip compile` writes.
const UV_HEADER: &str = "# This file was autogenerated by uv";
/// The requirements lock ward compiles.
const LOCK_TXT: &str = "requirements.lock.txt";

/// The [`LockedList`] of a uv run whose declared outputs are `outputs`:
/// `uv.lock`, ward's `requirements.lock.txt`, or another `.txt`
/// requirements file uv compiled (its header says so). The outputs name every lock the run may write, and it must leave
/// one.
/// `indexes` are the listed registries' index URLs and their routes, the
/// default first: each package is judged by the registry that served it, a
/// uv.lock package by its `source`, a compiled requirements pin by the
/// default (the one index uv is given).
pub(crate) fn locked_list<'a>(
    outputs: Vec<PathBuf>,
    indexes: Vec<(String, String)>,
) -> LockedList<'a> {
    Box::new(move |staged: &Staged<'_>| {
        let mut locked = Vec::new();
        let mut read = false;
        for output in &outputs {
            let name = output.file_name().and_then(|name| name.to_str());
            let requirements = name.is_some_and(|name| name.ends_with(".txt"));
            if name != Some("uv.lock") && !requirements {
                continue;
            }
            let Some(bytes) = staged.read(output)? else {
                continue;
            };
            let text = String::from_utf8_lossy(&bytes);
            // A requirements output is also a project input
            // (requirements.txt): only ward's own lock, or one uv
            // compiled, is a lock.
            let compiled = name == Some(LOCK_TXT) || text.starts_with(UV_HEADER);
            if requirements && !compiled {
                continue;
            }
            read = true;
            if requirements {
                let default = indexes.first().map(|(_, route)| route.clone());
                locked.extend(requirements_packages(&text)?.into_iter().map(
                    |package| match &default {
                        Some(route) => package.on_route(route.clone()),
                        None => package,
                    },
                ));
            } else {
                locked.extend(uv_pypi_packages(&text, &indexes)?.into_iter().map(
                    |(name, version, files, route)| {
                        LockedPackage::new(name, version)
                            .with_files(files)
                            .on_route(route)
                    },
                ));
            }
        }
        if !read {
            return Err(io::Error::new(
                io::ErrorKind::InvalidData,
                "the run left no uv.lock or requirements file",
            ));
        }
        Ok(locked)
    })
}

/// The exact `name==version` pins of a requirements file, compiled or
/// not, each line read on its own: a marker or a hash after the pin is
/// ignored. Comments, options, editable and path requirements, and URL or
/// VCS requirements (`name @ git+https://...`) are known and name no
/// registry package. Any other line (a range, an include of another file)
/// is `InvalidData`: a package this reader skipped would never be judged.
/// The tailor's own reader decides what the file may hold.
fn requirements_packages(text: &str) -> io::Result<Vec<LockedPackage>> {
    let mut found = Vec::new();
    for line in text.replace("\\\n", " ").lines() {
        let body = line.split(" #").next().unwrap_or("").trim();
        let first = body.split_whitespace().next().unwrap_or("");
        let include = matches!(first, "-r" | "-c" | "--requirement" | "--constraint")
            || ["-r", "-c", "--requirement=", "--constraint="]
                .iter()
                .any(|flag| first.len() > flag.len() && first.starts_with(flag));
        let known = body.is_empty()
            || body.starts_with('#')
            || (body.starts_with('-') && !include)
            || body.starts_with(['.', '/'])
            || body.contains(" @ ")
            || body.contains("://");
        if known {
            continue;
        }
        let pin = exact_pin(body).ok_or_else(|| {
            io::Error::new(
                io::ErrorKind::InvalidData,
                format!("the requirements file line {body:?} is not an exact registry pin"),
            )
        })?;
        found.push(pin);
    }
    Ok(found)
}

fn exact_pin(line: &str) -> Option<LockedPackage> {
    let line = line.split(" #").next()?.trim();
    let requirement = line.split(';').next()?.split_whitespace().next()?;
    let (name, version) = requirement.split_once("==")?;
    let name = name.split('[').next()?.trim();
    let plain = |word: &str, extra: &[u8]| {
        !word.is_empty()
            && word
                .bytes()
                .all(|b| b.is_ascii_alphanumeric() || b"._-".contains(&b) || extra.contains(&b))
    };
    (plain(name, b"") && plain(version, b"+!")).then(|| LockedPackage::new(name, version))
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn uv_locks_list_public_index_packages_only() {
        let lock = r#"version = 1
requires-python = ">=3.12"

[[package]]
name = "demo"
version = "0.1.0"
source = { editable = "." }

[[package]]
name = "six"
version = "1.17.0"
source = { registry = "https://pypi.org/simple" }
sdist = { url = "https://files.pythonhosted.org/packages/94/e7/six-1.17.0.tar.gz", hash = "sha256:ff70335d468e7eb6ec65b95b99d3a2836546063f63acc5171de367e834932a81" }
wheels = [
    { url = "https://files.pythonhosted.org/packages/b7/ce/six-1.17.0-py2.py3-none-any.whl", hash = "sha256:4721f391ed90541fddacab5acf947aa0d3dc7d27b2e1e8eda2be8970586c3274" },
]

[[package]]
name = "private"
version = "2.0.0"
source = { registry = "https://example.com/simple" }

[[package]]
name = "iniconfig"
version = "2.0.0"
source = { git = "https://github.com/pytest-dev/iniconfig?rev=v2.0.0#93f5930e668c0d1ddf4597e38dd0dea4e2665e7a" }
"#;
        let six = (
            "six".to_string(),
            "1.17.0".to_string(),
            vec![
                "six-1.17.0.tar.gz".to_string(),
                "six-1.17.0-py2.py3-none-any.whl".to_string(),
            ],
            "pypi".to_string(),
        );
        assert_eq!(
            uv_pypi_packages(lock, &[]).unwrap(),
            std::slice::from_ref(&six)
        );
        // A package from a listed index is judged too, by that index's
        // route, its URL compared as the policy compares index URLs.
        let listed = [(
            "https://EXAMPLE.com/simple/".to_string(),
            "pypi-corp".to_string(),
        )];
        assert_eq!(
            uv_pypi_packages(lock, &listed).unwrap(),
            [
                six,
                (
                    "private".to_string(),
                    "2.0.0".to_string(),
                    Vec::new(),
                    "pypi-corp".to_string()
                )
            ]
        );
    }

    #[test]
    fn compiled_requirements_list_their_pins() {
        let text = "six==1.17.0 \\\n    --hash=sha256:4721f391ed90541fddacab5acf947aa0d3dc7d27b2e1e8eda2be8970586c3274\n\
                    iniconfig @ git+https://github.com/pytest-dev/iniconfig@93f5930e668c0d1ddf4597e38dd0dea4e2665e7a\n\
                    # via demo\n--index-url https://pypi.org/simple\n-e ./local\n\
                    requests[socks]==2.32.3 ; python_version >= \"3\"\n\
                    torch==2.4.0+cpu  # a local version\n";
        assert_eq!(
            requirements_packages(text).unwrap(),
            [
                LockedPackage::new("six", "1.17.0"),
                LockedPackage::new("requests", "2.32.3"),
                LockedPackage::new("torch", "2.4.0+cpu"),
            ]
        );
        for unread in ["attrs>=23\n", "-r other.txt\n", "-rother.txt\n", "six\n"] {
            let error = requirements_packages(unread).unwrap_err();
            assert_eq!(error.kind(), io::ErrorKind::InvalidData, "{unread}");
        }
    }
}
