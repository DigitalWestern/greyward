#!/usr/bin/env python3
"""Generate and verify the popular-package lists the binary embeds.

`lookalike-name` (see DESIGNS.md, the policy table) flags a locked registry
package whose name is one edit away from a popular package's name without
being that package. Each tailor embeds its ecosystem's list as
`src/tailors/<tailor>/popular.txt`; this script is the only thing that
writes those files. For each ecosystem it:

1. fetches the named source below (a published ranking, or the registry's
   own API sorted by downloads);
2. keeps the first LIMIT distinct names in ranking order, distinct after the
   ecosystem's name normalization (the same rule the tailor applies before
   comparing, so two spellings of one name take one slot);
3. writes them one per line, sorted by their normalized form, under a header
   naming the source and the date.

The downloaded rankings are untrusted data: names are checked against each
registry's name grammar and anything else is dropped, never written.

Usage, from the repository root:

    python3 tools/popular.py              # every ecosystem
    python3 tools/popular.py python go    # just these
    python3 tools/popular.py --check      # verify the checked-in files, no network

`--check` verifies each checked-in file is what this script writes for the
names it holds: the header, the normalization, the order, no duplicates, and
the size. Rankings move daily, so `--check` does not compare against
upstream; regenerating is a deliberate refresh, reviewed like any data
change. Standard library only.
"""
import argparse
import datetime
import json
import os
import re
import sys
import time
import urllib.parse
import urllib.request

REPO = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
LIMIT = 2000
USER_AGENT = "greyward-popular-list (https://github.com/DigitalWestern/greyward)"
HEADER = "# Generated by tools/popular.py; do not edit by hand."


def normalize_python(name):
    """PEP 503: lowercase, every run of -, _ and . is one -."""
    return re.sub(r"[-_.]+", "-", name).lower()


def normalize_lower(name):
    return name.lower()


def normalize_cargo(name):
    """crates.io treats - and _ as one character, and case as none."""
    return name.lower().replace("_", "-")


def normalize_go(name):
    """A module path is compared whole and case-sensitively; its major
    version suffix (/v2, gopkg.in's .v3) is dropped, so one module's major
    versions are one name."""
    return re.sub(r"(/v[0-9]+|\.v[0-9]+)$", "", name)


def identity(name):
    return name


# name grammars: what each registry accepts, loosely. A ranking line that
# fails its grammar is dropped.
GRAMMAR = {
    "python": re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,200}$"),
    "node": re.compile(r"^(@[a-z0-9][a-z0-9._~-]*/)?[a-z0-9_][a-z0-9._~-]{0,213}$"),
    "cargo": re.compile(r"^[A-Za-z][A-Za-z0-9_-]{0,63}$"),
    "ruby": re.compile(r"^[A-Za-z0-9][A-Za-z0-9._-]{0,200}$"),
    "elixir": re.compile(r"^[a-z][a-z0-9_]{0,200}$"),
    "dotnet": re.compile(r"^[A-Za-z0-9_][A-Za-z0-9._-]{0,99}$"),
    "go": re.compile(r"^[A-Za-z0-9.-]+\.[A-Za-z]+(/[A-Za-z0-9._~-]+)+$"),
}


def http_get(url, accept="application/json"):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT, "Accept": accept})
    for attempt in range(4):
        try:
            with urllib.request.urlopen(request, timeout=120) as response:
                return response.read()
        except OSError as error:
            if attempt == 3:
                raise SystemExit(f"popular.py: {url}: {error}")
            time.sleep(2 * (attempt + 1))
    raise AssertionError("unreachable")


def fetch_json(url):
    return json.loads(http_get(url))


def python_names():
    rows = fetch_json("https://hugovk.dev/top-pypi-packages/top-pypi-packages.min.json")["rows"]
    return [row["project"] for row in rows]


def node_names():
    text = http_get(
        "https://raw.githubusercontent.com/wooorm/npm-high-impact/main/lib/top-download.js",
        accept="text/plain",
    ).decode()
    return re.findall(r"^\s*'([^']+)',?\s*$", text, re.M)


def cargo_names():
    names = []
    for page in range(1, LIMIT // 100 + 3):
        url = f"https://crates.io/api/v1/crates?sort=downloads&per_page=100&page={page}"
        names += [crate["name"] for crate in fetch_json(url)["crates"]]
        time.sleep(1)  # crates.io's crawler policy: one request a second
    return names


def ecosystems_names(registry, sort):
    names = []
    for page in range(1, 4):
        url = (
            f"https://packages.ecosyste.ms/api/v1/registries/{registry}/packages"
            f"?sort={sort}&order=desc&per_page=1000&page={page}"
        )
        names += [package["name"] for package in fetch_json(url)]
    return names


def ruby_names():
    return ecosystems_names("rubygems.org", "downloads")


def go_names():
    return ecosystems_names("proxy.golang.org", "dependent_packages_count")


def elixir_names():
    names = []
    for page in range(1, LIMIT // 100 + 3):
        url = f"https://hex.pm/api/packages?sort=total_downloads&page={page}"
        names += [package["name"] for package in fetch_json(url)]
    return names


def dotnet_names():
    found = []
    for skip in range(0, 3000, 1000):
        url = (
            "https://azuresearch-usnc.nuget.org/query?q=&prerelease=false"
            f"&semVerLevel=2.0.0&take=1000&skip={skip}"
        )
        found += [(entry["totalDownloads"], entry["id"]) for entry in fetch_json(url)["data"]]
    # The search ranks by relevance, which downloads dominate; the list is
    # the most downloaded of what it returned.
    found.sort(key=lambda pair: (-pair[0], pair[1].lower()))
    return [name for _, name in found]


# ecosystem: (tailor folder, source as the header names it, fetch, normalize)
SOURCES = {
    "python": (
        "python",
        "hugovk/top-pypi-packages (PyPI downloads, last 30 days)",
        python_names,
        normalize_python,
    ),
    "node": (
        "node",
        "wooorm/npm-high-impact top-download (npm downloads)",
        node_names,
        normalize_lower,
    ),
    "cargo": (
        "cargo",
        "crates.io API, crates sorted by all-time downloads",
        cargo_names,
        normalize_cargo,
    ),
    "ruby": (
        "ruby",
        "packages.ecosyste.ms, rubygems.org packages sorted by downloads",
        ruby_names,
        normalize_lower,
    ),
    "go": (
        "go",
        "packages.ecosyste.ms, proxy.golang.org modules sorted by dependent packages "
        "(Go publishes no download counts)",
        go_names,
        normalize_go,
    ),
    "elixir": (
        "elixir",
        "hex.pm API, packages sorted by total downloads",
        elixir_names,
        identity,
    ),
    "dotnet": (
        "dotnet",
        "NuGet search API, packages sorted by total downloads",
        dotnet_names,
        normalize_lower,
    ),
}


def path_of(eco):
    return os.path.join(REPO, "src", "tailors", SOURCES[eco][0], "popular.txt")


def select(eco, ranked):
    """The first LIMIT valid names, distinct after normalization, sorted by
    the normalized form (then the spelling, so the order is total)."""
    _, _, _, normalize = SOURCES[eco]
    grammar = GRAMMAR[eco]
    seen = set()
    kept = []
    for name in ranked:
        if not isinstance(name, str) or not grammar.match(name):
            continue
        key = normalize(name)
        if key in seen:
            continue
        seen.add(key)
        kept.append(name)
        if len(kept) == LIMIT:
            break
    return sorted(kept, key=lambda name: (normalize(name), name))


def render(eco, names, date):
    _, source, _, _ = SOURCES[eco]
    lines = [
        HEADER,
        f"# Source: {source}.",
        f"# Fetched: {date}. The {len(names)} most popular names, sorted.",
    ]
    return "\n".join(lines + names) + "\n"


def parse(text):
    lines = text.splitlines()
    header = [line for line in lines if line.startswith("#")]
    names = [line for line in lines if line and not line.startswith("#")]
    return header, names


def check(eco):
    path = path_of(eco)
    try:
        with open(path, encoding="utf-8") as handle:
            text = handle.read()
    except FileNotFoundError:
        return [f"{path}: missing; run python3 tools/popular.py {eco}"]
    header, names = parse(text)
    problems = []
    match = re.match(r"^# Fetched: (\d{4}-\d{2}-\d{2})\.", header[2] if len(header) > 2 else "")
    if not match:
        return [f"{path}: the header has no fetch date"]
    expected = render(eco, select(eco, names), match.group(1))
    if len(names) != LIMIT:
        problems.append(f"{path}: {len(names)} names, expected {LIMIT}")
    if text != expected:
        problems.append(f"{path}: not in the canonical form tools/popular.py writes")
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("ecosystems", nargs="*", help=", ".join(SOURCES))
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    unknown = [eco for eco in args.ecosystems if eco not in SOURCES]
    if unknown:
        parser.error(f"unknown ecosystem(s): {', '.join(unknown)}; choose from {', '.join(SOURCES)}")
    ecosystems = args.ecosystems or list(SOURCES)
    if args.check:
        problems = [problem for eco in ecosystems for problem in check(eco)]
        for problem in problems:
            print(problem, file=sys.stderr)
        return 1 if problems else 0
    date = datetime.date.today().isoformat()
    for eco in ecosystems:
        _, _, fetch, _ = SOURCES[eco]
        names = select(eco, fetch())
        if len(names) < LIMIT:
            raise SystemExit(f"popular.py: {eco}: only {len(names)} valid names")
        with open(path_of(eco), "w", encoding="utf-8") as handle:
            handle.write(render(eco, names, date))
        print(f"{eco}: {len(names)} names -> {os.path.relpath(path_of(eco), REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
